'use strict';

/**
 * Sends a prompt directly to Google Gemini's REST API endpoint.
 *
 * @param {string} prompt - Text prompt for Gemini
 * @returns {Promise<string>} - Text generated by Gemini
 */
async function callGemini(prompt) {
  const apiKey = process.env.GEMINI_API_KEY || '';

  if (!apiKey || apiKey === 'your_gemini_api_key_here') {
    throw new Error('GEMINI_API_KEY is not configured in .env');
  }

  const model = process.env.GEMINI_MODEL || 'gemini-3.8-flash';
  const timeoutMs = parseInt(process.env.GEMINI_TIMEOUT || '30000', 10);
  const url = `https://generativelanguage.googleapis.com/v1/models/${model}:generateContent?key=${apiKey}`;

  const body = {
    contents: [
      {
        parts: [{ text: prompt }]
      }
    ],
    generationConfig: {
      temperature: 0.3,
      maxOutputTokens: 800
    }
  };

  const response = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
    signal: AbortSignal.timeout(timeoutMs)
  });

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(`Google Gemini API error (${response.status}): ${errorText}`);
  }

  const data = await response.json();
  const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;
  return text || 'No response generated from Gemini.';
}

/**
 * Generates plain-language English and Hindi explanations for a matched scheme.
 *
 * @param {Object} scheme - Scheme document
 * @param {Object} applicant - Applicant profile details
 * @returns {Promise<{ explanation_en: string, explanation_hi: string }>}
 */
async function explainScheme(scheme, applicant) {
  const apiKey = process.env.GEMINI_API_KEY || '';
  if (!apiKey || apiKey === 'your_gemini_api_key_here') {
    // Return statutory rule-grounded fallback explanations if API key is unconfigured
    return {
      explanation_en: `Based on your profile, ${scheme.name} is your best match. Your project cost of ₹${(applicant.project_cost || 0).toLocaleString('en-IN')} is within the scheme ceiling and your annual family income is under the statutory eligibility cap.`,
      explanation_hi: `आपके प्रोफाइल के अनुसार, ${scheme.name} आपके लिए सबसे उपयुक्त योजना है। आपकी प्रोजेक्ट लागत (₹${(applicant.project_cost || 0).toLocaleString('en-IN')}) योजना की सीमा के भीतर है।`,
    };
  }

  const prompt = `You are Yojana Setu, an empathetic welfare assistant explaining government credit schemes to marginalized entrepreneurs in India.

Scheme Details:
- Name: ${scheme.name} (${scheme.code})
- Agency: ${scheme.provider}
- Category: ${scheme.beneficiary_category}
- Max Loan: ₹${scheme.max_loan_amount || 'N/A'}
- Concessional Interest Rate: ${scheme.beneficiary_interest_rate || 'N/A'}% p.a.
- Description: ${scheme.description}

Applicant Profile:
- Name: ${applicant.name || 'Applicant'}
- Caste/Category: ${applicant.category}
- Proposed Business: ${applicant.business_type} (${applicant.business_description || ''})
- Project Cost: ₹${applicant.project_cost}
- Annual Family Income: ₹${applicant.annual_family_income}

Provide a short, direct explanation of WHY this scheme matches them in 2 clear sentences.
Format strictly as JSON with two keys:
{"explanation_en": "English explanation", "explanation_hi": "हिन्दी में स्पष्टीकरण"}
Only output valid JSON.`;

  try {
    const raw = await callGemini(prompt);
    const cleaned = raw.replace(/```json/g, '').replace(/```/g, '').trim();
    const parsed = JSON.parse(cleaned);
    return {
      explanation_en: parsed.explanation_en,
      explanation_hi: parsed.explanation_hi,
    };
  } catch (err) {
    console.warn('Gemini explanation fallback:', err.message);
    return {
      explanation_en: `Based on your profile, ${scheme.name} is your best match. Your project cost of ₹${(applicant.project_cost || 0).toLocaleString('en-IN')} is within the scheme ceiling and your annual family income is under the statutory eligibility cap.`,
      explanation_hi: `आपके प्रोफाइल के अनुसार, ${scheme.name} आपके लिए सबसे उपयुक्त योजना है। आपकी प्रोजेक्ट लागत (₹${(applicant.project_cost || 0).toLocaleString('en-IN')}) योजना की सीमा के भीतर है।`,
    };
  }
}

/**
 * Explains any welfare or credit scheme topic directly using Gemini.
 *
 * @param {string} topic - The topic or question to explain
 * @returns {Promise<string>}
 */
async function explainTopic(topic) {
  const prompt = `You are Yojana Setu AI. Explain the following government scheme topic or question concisely in 2-3 simple sentences for a first-time applicant:
Topic: "${topic}"
Keep it clear, actionable, and free of legal jargon.`;

  return callGemini(prompt);
}

module.exports = {
  callGemini,
  explainScheme,
  explainTopic,
};
